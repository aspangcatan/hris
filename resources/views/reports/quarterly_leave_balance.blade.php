@section('js')
<script>
    const ROUTE_DIVISIONS  = "{{ route('getDivisionList') }}";
    const ROUTE_SECTIONS   = "{{ route('getSectionList') }}";
    const ROUTE_REPORT     = "{{ route('report.quarterly_leave_balance.data') }}";
    const ROUTE_HISTORY    = "{{ route('report.quarterly_leave_balance.history') }}";
    const ROUTE_SNAPSHOT   = "{{ route('report.quarterly_leave_balance.snapshot', ':id') }}";
    const ROUTE_PDF        = "{{ route('report.quarterly_leave_balance.pdf', ':id') }}";

    const QUARTER_LABELS = { 1: 'Q1 (Jan–Mar)', 2: 'Q2 (Apr–Jun)', 3: 'Q3 (Jul–Sep)', 4: 'Q4 (Oct–Dec)' };

    $(document).ready(function () {
        loadDivisions();
        loadHistory();

        $('#filter_division').on('change', function () {
            const divId = $(this).val();
            $('#filter_section').html('<option value="">All Sections</option>');
            if (!divId) return;
            fetch(`${ROUTE_SECTIONS}?division=${divId}`)
                .then(r => r.json())
                .then(data => data.forEach(s =>
                    $('#filter_section').append(`<option value="${s.id}">${s.description}</option>`)
                ));
        });

        $('#btn_generate').on('click', generateReport);
        $('#btn_refresh_history').on('click', loadHistory);
    });

    function loadDivisions() {
        fetch(ROUTE_DIVISIONS)
            .then(r => r.json())
            .then(data => data.forEach(d =>
                $('#filter_division').append(`<option value="${d.id}">${d.description}</option>`)
            ));
    }

    async function generateReport() {
        const year     = $('#filter_year').val();
        const quarter  = $('#filter_quarter').val();
        const division = $('#filter_division').val();
        const section  = $('#filter_section').val();

        if (!year || !quarter) {
            toastr.warning('Please select Year and Quarter.', 'Required');
            return;
        }

        $('#btn_generate').prop('disabled', true).html('<span class="spinner-border spinner-border-sm me-1"></span> Generating...');

        try {
            const params = new URLSearchParams({ year, quarter });
            if (division) params.append('division', division);
            if (section)  params.append('section',  section);

            const resp = await fetch(`${ROUTE_REPORT}?${params}`);
            const data = await resp.json();

            if (data.error) { toastr.error(data.error, 'Error'); return; }

            const rows = Array.isArray(data) ? data : (data.rows || []);
            const $body = $('#report_body').empty();

            if (!rows.length) {
                $body.html('<tr><td colspan="5" class="text-center text-muted py-3">No leave credits found for the selected filters.</td></tr>');
            } else {
                rows.forEach(r => {
                    const name   = fullName(r);
                    const bal    = parseFloat(r.balance || 0);
                    const balCls = bal < 0 ? 'text-danger' : '';
                    $body.append(`
                        <tr>
                            <td>${name}</td>
                            <td>${r.division_name || '—'}</td>
                            <td>${r.section_name  || '—'}</td>
                            <td>${r.leave_type}</td>
                            <td class="text-end ${balCls}">${fmt(bal)}</td>
                        </tr>
                    `);
                });
            }

            const qLabel = QUARTER_LABELS[quarter] || `Q${quarter}`;
            $('#report_label').text(`${qLabel} · ${year}`);
            $('#report_container').removeClass('d-none');

            // Wire up PDF button if snapshot was saved
            if (data.snapshot_id) {
                const pdfUrl = ROUTE_PDF.replace(':id', data.snapshot_id);
                $('#btn_print_pdf').attr('href', pdfUrl);
            }

            toastr.success('Report saved to history.', 'Saved');
            loadHistory();
        } catch (e) {
            toastr.error('Failed to load report.', 'Error');
        } finally {
            $('#btn_generate').prop('disabled', false).html('<i class="bi bi-bar-chart-line"></i> Generate');
        }
    }

    async function loadHistory() {
        $('#history_body').html('<tr><td colspan="6" class="text-center text-muted py-2">Loading…</td></tr>');
        try {
            const resp = await fetch(ROUTE_HISTORY);
            const data = await resp.json();

            if (data.error) {
                $('#history_body').html(`<tr><td colspan="6" class="text-danger text-center">${data.error}</td></tr>`);
                return;
            }

            if (!data.length) {
                $('#history_body').html('<tr><td colspan="6" class="text-center text-muted py-3">No generated reports yet.</td></tr>');
                return;
            }

            const $tbody = $('#history_body').empty();
            data.forEach(h => {
                const qLabel = QUARTER_LABELS[h.quarter] || `Q${h.quarter}`;
                const genBy  = h.gen_lname ? `${h.gen_lname}, ${h.gen_fname}` : '—';
                const genAt  = h.created_at ? new Date(h.created_at).toLocaleString() : '—';
                const pdfUrl = ROUTE_PDF.replace(':id', h.id);
                $tbody.append(`
                    <tr>
                        <td>${h.year} · ${qLabel}</td>
                        <td>${h.division_name || 'All'}</td>
                        <td>${h.section_name  || 'All'}</td>
                        <td>${genBy}</td>
                        <td>${genAt}</td>
                        <td class="text-end">
                            <button class="btn btn-sm btn-outline-primary py-0 px-2 me-1"
                                    onclick="viewSnapshot(${h.id}, '${h.year}', ${h.quarter})">
                                <i class="bi bi-eye"></i> View
                            </button>
                            <a href="${pdfUrl}" target="_blank" class="btn btn-sm btn-outline-danger py-0 px-2">
                                <i class="bi bi-file-earmark-pdf"></i> PDF
                            </a>
                        </td>
                    </tr>
                `);
            });
        } catch (e) {
            $('#history_body').html('<tr><td colspan="6" class="text-danger text-center">Failed to load history.</td></tr>');
        }
    }

    async function viewSnapshot(id, year, quarter) {
        const qLabel = QUARTER_LABELS[quarter] || `Q${quarter}`;
        $('#snapshot_modal_title').text(`${year} · ${qLabel}`);
        $('#snapshot_body').html('<tr><td colspan="5" class="text-center text-muted">Loading…</td></tr>');
        $('#btn_snapshot_pdf').attr('href', ROUTE_PDF.replace(':id', id));
        const modal = new bootstrap.Modal(document.getElementById('snapshot_modal'));
        modal.show();

        try {
            const url  = ROUTE_SNAPSHOT.replace(':id', id);
            const resp = await fetch(url);
            const data = await resp.json();

            if (data.error) {
                $('#snapshot_body').html(`<tr><td colspan="5" class="text-danger">${data.error}</td></tr>`);
                return;
            }

            const rows = data.rows || [];
            const $tbody = $('#snapshot_body').empty();

            if (!rows.length) {
                $tbody.html('<tr><td colspan="5" class="text-center text-muted py-3">No data in snapshot.</td></tr>');
                return;
            }

            rows.forEach(r => {
                const name   = fullName(r);
                const bal    = parseFloat(r.balance || 0);
                const balCls = bal < 0 ? 'text-danger' : '';
                $tbody.append(`
                    <tr>
                        <td>${name}</td>
                        <td>${r.division_name || '—'}</td>
                        <td>${r.section_name  || '—'}</td>
                        <td>${r.leave_type_name}</td>
                        <td class="text-end ${balCls}">${fmt(bal)}</td>
                    </tr>
                `);
            });
        } catch (e) {
            $('#snapshot_body').html('<tr><td colspan="5" class="text-danger">Failed to load snapshot.</td></tr>');
        }
    }

    function fullName(r) {
        const mi = r.mname ? r.mname.charAt(0).toUpperCase() + '.' : '';
        return [r.lname + ',', r.fname, mi].filter(Boolean).join(' ');
    }

    function fmt(val) {
        const n = parseFloat(val || 0);
        return isNaN(n) ? '0.000' : n.toFixed(3);
    }
</script>
@stop
